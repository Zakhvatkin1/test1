package main

import (
	"bufio"
	"fmt"
	"math/rand"
	"os"
	"strconv"
	"strings"
	"time"
)

func main() {
	// Инициализируем генератор случайных чисел
	rand.Seed(time.Now().UnixNano())

	// Создаём игровое поле 10x1
	field := [10]string{}
	for i := range field {
		field[i] = "~" // Символ воды
	}
	// Размещаем корабль (4 палубы)
	shipStart := rand.Intn(7) // Максимальная позиция начала корабля - 6, чтобы корабль поместился на созданное нами поле
	for i := 0; i < 4; i++ {
		field[shipStart+i] = "O" // Символ корабля (скрытый от игрока)
	}

	// Создаём поле, видимое игроку
	visibleField := [10]string{}
	for i := range visibleField {
		visibleField[i] = "~"
	}
	// Добавляем счетчик попаданий
	hits := 0

	// Основной игровой цикл
	scanner := bufio.NewScanner(os.Stdin)
	fmt.Println("Добро пожаловать в игру 'Морской бой'!")
	fmt.Println("На поле размером 10x1 спрятан корабль из 4 палуб.")
	fmt.Println("Введи координату от 0 до 9, чтобы выстрелить.")

	for hits < 4 {
		// Отображение текущего состояния поля
		fmt.Print("Поле: ")
		for _, cell := range visibleField {
			fmt.Print(cell + " ")
		}
		fmt.Println()
		// Получение координаты от пользователя
		fmt.Print("Введите координату выстрела (0-9): ")
		scanner.Scan()
		input := scanner.Text()

		// Проверка ввода
		coord, err := strconv.Atoi(strings.TrimSpace(input))
		if err != nil || coord < 0 || coord > 9 {
			fmt.Println("Неверная координата! Введите число от 0 до 9.")
			continue
		}
		// Проверка попадания
		if field[coord] == "O" && visibleField[coord] != "X" {
			fmt.Println("Вы попали!")
			visibleField[coord] = "X" // Отметка попадания
			hits++
		} else if visibleField[coord] == "X" {
			fmt.Println("Вы уже стреляли в эту клетку!")
		} else {
			fmt.Println("Вы промахнулись!")
			visibleField[coord] = "•" // Отметка промаха
		}
	}

	// Отображение финального состояния поля
	fmt.Print("Финальное поле: ")
	for _, cell := range visibleField {
		fmt.Print(cell + " ")
	}
	fmt.Println()

	fmt.Println("Поздравляем! Вы выиграли!")
	fmt.Println("Корабль находился на позициях:")
	for i, cell := range field {
		if cell == "O" {
			fmt.Printf("%d ", i)
		}
	}
	fmt.Println()
}

