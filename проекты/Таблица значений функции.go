package main

import (
	"fmt"
	"math"
)

func main() {
	fmt.Println("Таблица значений функции y = 5 - x²/2 на отрезке [-3; 3] с шагом 0.3:")
	fmt.Printf("%-6s | %-6s\n", "x", "y")
	fmt.Println("---------------")

	for x := -3.0; x <= 3.0; x += 0.3 {
		// Вычисляем значение функции y = 5 - x²/2 для текущего x
		y := 5 - x*x/2
		// Выводим значения x (округленное до 1 знака) и y (с 2 знаками после запятой)
		fmt.Printf("%-6.1f | %-6.2f\n", math.Round(x*10)/10, y)
	}
}
