//Объявили переменную number (целое число).
//
//fmt.Print("Введите целое число: ") — Выводим на экран в строку сообщение ввести целое число.
//
//C помощью fmt.Scan(&number) считываем введённое пользователем значение и сохраняем его в переменной number. Оператор & получает адрес переменной в памяти.
//
//if number%2 == 0 { — синтаксис проверяет, является ли число чётным, используя оператор остатка от деления (%). Если остаток от деления на 2 равен 0, число чётное.
