package main

import (
	"fmt"
)

func main() {
	var number int
	fmt.Print("Введите целое число: ")
	fmt.Scan(&number)

	if number%2 == 0 {
		fmt.Println("Число", number, "чётное")
	} else {
		fmt.Println("Число", number, "нечётное")
	}
}

